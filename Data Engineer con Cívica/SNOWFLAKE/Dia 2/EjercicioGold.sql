    A.STATE,
    SUM(O.ORDER_COST) AS TOTAL_ORDER_COSTS,
    COUNT(O.ORDER_ID) AS NUMBER_OF_ORDERS,
    COUNT(DISTINCT O.USER_ID) AS NUMBER_OF_USERS,
    SUM(O.SHIPPING_COST) / SUM(O.ORDER_COST) * 100 AS SHIPPING_COST_PERCENTAGE,
    MODE(O.SHIPPING_SERVICE) AS MAIN_SHIPPING_SERVICE
