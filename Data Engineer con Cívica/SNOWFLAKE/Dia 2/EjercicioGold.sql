-- PROCEDURE GOLD
CREATE OR REPLACE PROCEDURE INSERT_GOLD_PROCEDURE()
    RETURNS VARCHAR
    LANGUAGE SQL
    EXECUTE AS CALLER
AS
BEGIN
    TRUNCATE TABLE DEV_CURSO_BRZ_DB_ALUMNO_29.GOLD.SESSION_DETAILS;
    TRUNCATE TABLE DEV_CURSO_BRZ_DB_ALUMNO_29.GOLD.GENERAL_STATE_ANALYSIS;

    INSERT INTO GOLD.SESSION_DETAILS
    SELECT
        SESSION_ID,
        BOOLOR_AGG(ORDER_ID IS NOT NULL),
        MAX(HIT_NUMBER),
        DATEDIFF(MINUTE, MIN(CREATED_AT), MAX(CREATED_AT))
    FROM SILVER.EVENTS
    GROUP BY SESSION_ID;

    INSERT INTO GOLD.GENERAL_STATE_ANALYSIS
    SELECT
        A.STATE,
        SUM(O.ORDER_COST),
        COUNT(O.ORDER_ID),
        COUNT(DISTINCT O.USER_ID),
        SUM(O.SHIPPING_COST) / SUM(O.ORDER_COST) * 100,
        MODE(O.SHIPPING_SERVICE)
    FROM SILVER.ORDERS O
    JOIN SILVER.ADDRESSES A ON O.ADDRESS_ID = A.ADDRESS_ID
    GROUP BY A.STATE;

    RETURN 'Gold insertado con éxito máquina';
END;

CALL INSERT_GOLD_PROCEDURE();

